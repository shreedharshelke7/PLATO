/**
 * Fuzzy search through bundled food database.
 */
export function searchLocalFoods(query: string, limit: number = 20): FoodItem[] {
  const cleanQ = query.trim().toLowerCase();
  if (!cleanQ) return LOCAL_FOODS.slice(0, limit);

  const tokens = cleanQ.split(/\s+/).filter(Boolean);

  const scored = LOCAL_FOODS.map((item) => {
    let score = 0;
    const itemName = item.name.toLowerCase();

    // Exact matches
    if (itemName === cleanQ) score += 100;
    else if (itemName.includes(cleanQ)) score += 50;

    for (const token of tokens) {
      if (itemName.includes(token)) score += 20;
      for (const kw of item.keywords) {
        if (kw === token) score += 25;
        else if (kw.includes(token)) score += 10;
      }
    }

    return { item, score };
  })
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score);

  return scored.slice(0, limit).map((e) => e.item);
}
